/**
 * ฟังก์ชันช่วยค้นหาข้อมูลธนาคารจากชื่อ หรือ รหัสย่อ
 */
export function findBank(bankNameOrCode) {
  if (!bankNameOrCode) return null;
  const query = String(bankNameOrCode).trim().toLowerCase();
  return THAI_BANKS.find(b => 
    b.code.toLowerCase() === query ||
    b.officialName.toLowerCase() === query ||
    b.nameTh.toLowerCase() === query ||
    b.shortName.toLowerCase() === query ||
    query.includes(b.code.toLowerCase())
  ) || null;
}
